package com.carflip.copilot

/**
 * General game-level advisor.
 * It is intentionally independent from vehicle/plate analysis:
 * the same engine can say what to do, what to postpone, or what not to spend on.
 */
object GeneralGameAdvisor {
    fun analyze(context: android.content.Context, text: String, balance: Long?, garage: Int?): Opportunity? {
        val s = text.lowercase()
        val screen = GameParser.screenType(text)

        // Explicit urgent events have priority over optimization.
        if (GameParser.rewardAmount(text) != null ||
            listOf("получи награду", "забери награду", "награда доступна", "бонус доступен")
                .any { s.contains(it) }) {
            return Opportunity(
                "ПОЛУЧИТЬ НАГРАДУ",
                "Есть доступная награда",
                "Сначала забери уже доступную награду. Новые покупки и вложения сейчас не приоритетны, пока награда не получена.",
                96
            )
        }

        if (listOf("энергия полностью", "энергия восстановлена", "energy full", "energy restored")
                .any { s.contains(it) }) {
            return Opportunity(
                "ИСПОЛЬЗОВАТЬ ЭНЕРГИЮ",
                "Есть доступная энергия",
                "Сейчас есть ресурс, который можно потратить на полезное игровое действие. Не оставляй восстановленную энергию без причины.",
                88
            )
        }

        if (screen == "ЗАДАНИЕ" || screen == "КОНТРАКТ" ||
            listOf("новое задание", "новый контракт", "контракт доступен", "задание доступно")
                .any { s.contains(it) }) {
            return Opportunity(
                "ПРОВЕРИТЬ ЗАДАНИЕ",
                "Доступна игровая цель",
                "Сначала сравни награду, требования, срок и неизбежные расходы. Не покупай автомобиль или улучшения только ради задания, пока экономика не подтверждена.",
                93
            )
        }

        if (screen == "МАГАЗИН") {
            return Opportunity(
                "НЕ ПОКУПАТЬ СРАЗУ",
                "Открыт магазин",
                "Сначала сравни цену с текущим балансом, будущей выгодой и альтернативными расходами. Покупка сама по себе не является причиной тратить деньги.",
                89
            )
        }

        if (screen == "СОРЕВНОВАНИЕ") {
            return Opportunity(
                "СРАВНИТЬ НАГРАДУ",
                "Доступно испытание",
                "Проверь входные затраты, риск потери ресурсов и награду. Если затрат больше подтверждённой выгоды — отложи участие.",
                88
            )
        }

        if (screen == "ФИНАНСЫ") {
            return Opportunity(
                "КОНТРОЛИРОВАТЬ РАСХОДЫ",
                "Финансовый экран",
                "Сейчас важнее сохранить полный учёт денег: покупки, комиссии, продления, ремонт, улучшения и фактические выплаты.",
                91
            )
        }

        if (screen == "АУКЦИОН" || screen == "АУКЦИОН_НОМЕРА") {
            return Opportunity(
                "НЕ ПОВЫШАТЬ СРАЗУ",
                "Идут торги",
                "Перед новой ставкой сравни текущую полную себестоимость, комиссию и ожидаемую выплату. Если данных недостаточно — сначала собрать данные.",
                90
            )
        }

        if (garage != null && garage >= 3 && (s.contains("куп") || s.contains("аукцион") || screen == "ГАРАЖ")) {
            return Opportunity(
                "НЕ ПОКУПАТЬ СЕЙЧАС",
                "Гараж заполнен",
                "Сначала реши судьбу уже имеющихся автомобилей. Новая покупка при заполненном гараже может привести к лишним расходам или потере выгодной возможности.",
                95
            )
        }

        if (balance != null && balance <= 0L) {
            return Opportunity(
                "НЕ ТРАТИТЬ",
                "Нет свободного баланса",
                "Сейчас приоритет — получить деньги или награду и не создавать новые расходы.",
                99
            )
        }

        // If the screen contains an explicit spending action, warn before the vehicle engine.
        if (listOf("купить", "покупка", "улучшить", "улучшение", "ремонт", "тюнинг", "оплатить", "ставка")
                .any { s.contains(it) }) {
            return Opportunity(
                "СНАЧАЛА ПОСЧИТАТЬ",
                "Предстоит расход",
                "Перед оплатой сравни стоимость действия с ожидаемой выгодой. Если результат нельзя подтвердить цифрами, лучше отложить расход.",
                87
            )
        }

        if (listOf("магазин", "гараж", "работа", "задание", "контракт", "аукцион", "новости", "бонус")
                .any { s.contains(it) }) {
            return Opportunity(
                "ПРОВЕРИТЬ ВЫГОДУ",
                "Есть несколько игровых возможностей",
                "Copilot отслеживает не только автомобили и номера: задания, контракты, работу, магазин, аукционы, бонусы, новости, ресурсы и расходы.",
                78
            )
        }

        return null
    }
}
