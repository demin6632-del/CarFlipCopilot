package com.carflip.copilot

/**
 * Универсальный классификатор экранов/разделов игры.
 * Основан на реальных названиях кнопок и разделов из записи игры.
 * Не привязан к конкретной марке автомобиля.
 */
object GameScreenClassifier {
    private data class Rule(val type: String, val words: List<String>)

    private val rules = listOf(
        Rule("АУКЦИОН_НОМЕРОВ", listOf("аукцион номеров", "аукцион госномеров", "выставить на аукцион", "госномер", "госномер выставлен")),
        Rule("СКЛАД_НОМЕРОВ", listOf("склад номеров", "номер на складе", "снять номер со склада", "снять номер")),
        Rule("РЫНОК_АВТО", listOf("рынок авто", "рынок автомобилей", "авторынок", "машины на рынке")),
        Rule("АВТОСАЛОН", listOf("автосалон", "салон автомобилей")),
        Rule("ИМПОРТ_ТАМОЖНЯ", listOf("импорт с таможни", "таможн", "растамож", "таможня")),
        Rule("БИЗНЕСЫ", listOf("бизнесы", "бизнес", "доход бизнеса", "окупаемость бизнеса")),
        Rule("РАБОТА", listOf("работа", "зарплата", "заработок", "смена работы")),
        Rule("КЛАНЫ", listOf("кланы", "клановая", "вступить в клан", "покинуть клуб", "синдикат")),
        Rule("ПАРЫ_С_КОНКУРЕНТАМИ", listOf("пары с конкурентами", "пара с конкурентом", "конкурент", "pvp")),
        Rule("УЛИЧНЫЕ_ГОНКИ", listOf("уличные гонки", "уличной гонки", "заезд", "гонка", "гонк")),
        Rule("РЕФЕРАЛЫ", listOf("рефералы", "реферал", "пригласить", "приглашенные")),
        Rule("ГАРАЖНАЯ_НАГРАДА", listOf("гаражная награда", "награда гаража", "гаражная наград")),
        Rule("ТОП_ИГРОКОВ", listOf("топ игроков", "топ игроков", "рейтинг игроков", "самые богатые", "быстрые авто")),
        Rule("СХОДКА_У_ТЦ", listOf("сходка у тц", "сходка у тц", "тц")),
        Rule("ЧАСТНЫЕ_АВТОРЫНКИ", listOf("частные авторынки", "частный авторынок", "частный рынок")),
        Rule("ФИНАНСОВЫЙ_СЕКТОР", listOf("финансовый сектор", "финансы", "кредит", "банк", "вклад", "инвестиции")),
        Rule("ПРОФИЛЬ", listOf("профиль", "уровень", "репутация", "опыт")),
        Rule("ГАРАЖ", listOf("гараж", "мой гараж", "место в гараже")),
        Rule("МАГАЗИН_УСЛУГ", listOf("автомойка", "малярный цех", "шиномонтаж", "детейлинг", "запчасти", "купить автомойка", "купить запчасти")),
        Rule("КОНТРАКТ_ЗАДАНИЕ", listOf("контракт", "заказ", "квест", "миссия", "задание")),
        Rule("НАГРАДА", listOf("награда", "бонус", "приз", "выигрыш", "reward", "bonus")),
        Rule("ПРОДАЖА", listOf("продать", "продажа", "продан", "продано", "предложение покупателя", "купил")),
        Rule("ПОКУПКА", listOf("купить", "покупка", "куплен", "цена покупки", "покупатель", "buy")),
        Rule("УЛУЧШЕНИЕ", listOf("ремонт", "полировка", "окраска", "турбина", "чип", "тюнинг", "улучшение", "диагностика", "шины", "тормоза", "подвеска")),
        Rule("СОРЕВНОВАНИЕ", listOf("соревнование", "испытание", "challenge"))
    )

    fun classify(text: String): String {
        val s = text.lowercase()
        val match = rules.firstOrNull { rule -> rule.words.any { s.contains(it) } }
        if (match != null) return match.type
        if (GameParser.plateAuction(text)) return "АУКЦИОН_НОМЕРОВ"
        if (GameParser.carAuction(text)) return "АУКЦИОН_АВТО"
        if (GameParser.name(text).isNotBlank() || GameParser.price(text) != null || GameParser.hp(text) != null || GameParser.plate(text).isNotBlank()) return "АВТО"
        return "ОБЗОР"
    }

    fun isNavigationSection(type: String): Boolean = type in setOf(
        "ПРОФИЛЬ", "ГАРАЖ", "СКЛАД_НОМЕРОВ", "РЫНОК_АВТО", "АВТОСАЛОН",
        "АУКЦИОН_НОМЕРОВ", "ИМПОРТ_ТАМОЖНЯ", "БИЗНЕСЫ", "РАБОТА", "КЛАНЫ",
        "ПАРЫ_С_КОНКУРЕНТАМИ", "УЛИЧНЫЕ_ГОНКИ", "РЕФЕРАЛЫ", "ГАРАЖНАЯ_НАГРАДА",
        "ТОП_ИГРОКОВ", "СХОДКА_У_ТЦ", "ЧАСТНЫЕ_АВТОРЫНКИ", "ФИНАНСОВЫЙ_СЕКТОР"
    )
}
