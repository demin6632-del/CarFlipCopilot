package com.carflip.copilot

/**
 * Универсальный классификатор экранов/разделов игры.
 * Важный момент: нижнее меню игры постоянно присутствует на экране,
 * поэтому одиночные слова вроде «Гараж» или «Профиль» не используются
 * как доказательство текущего раздела.
 */
object GameScreenClassifier {
    private data class Rule(val type: String, val words: List<String>, val minHits: Int = 1)

    private val rules = listOf(
        Rule("АУКЦИОН_НОМЕРОВ", listOf("аукцион номеров", "аукцион госномеров", "выставить на аукцион", "госномер выставлен", "склада")),
        Rule("СКЛАД_НОМЕРОВ", listOf("склад номеров", "номер на складе", "снять номер со склада")),
        Rule("РЫНОК_АВТО", listOf("рынок авто", "рынок автомобилей", "авторынок", "машины на рынке")),
        Rule("АВТОСАЛОН", listOf("автосалон", "салон автомобилей")),
        Rule("ИМПОРТ_ТАМОЖНЯ", listOf("импорт с таможни", "растамож", "таможенная стоимость", "таможня")),
        Rule("БИЗНЕСЫ", listOf("бизнесы", "доход бизнеса", "окупаемость бизнеса", "открыть бизнес")),
        Rule("РАБОТА", listOf("зарплата", "рабочая смена", "место работы", "выбрать работу", "доход за смену")),
        Rule("КЛАНЫ", listOf("клановая среда", "вступить в клан", "покинуть клуб", "клановый статус", "синдикат")),
        Rule("ПАРЫ_С_КОНКУРЕНТАМИ", listOf("пары с конкурентами", "пара с конкурентом", "спор за влияние", "pvp")),
        Rule("УЛИЧНЫЕ_ГОНКИ", listOf("уличные гонки", "формат дуэли", "выбери формат дуэли", "заезд", "гонка")),
        Rule("РЕФЕРАЛЫ", listOf("рефералы", "пригласить друга", "реферальная система", "приглашенные")),
        Rule("ГАРАЖНАЯ_НАГРАДА", listOf("гаражная награда", "награда гаража", "получи награду за гараж")),
        Rule("ТОП_ИГРОКОВ", listOf("топ игроков", "самые богатые", "быстрые авто", "рейтинг игроков")),
        Rule("СХОДКА_У_ТЦ", listOf("сходка у тц", "сходка у тц", "место встречи у тц")),
        Rule("ЧАСТНЫЕ_АВТОРЫНКИ", listOf("частные авторынки", "частный авторынок", "частный рынок")),
        Rule("ФИНАНСОВЫЙ_СЕКТОР", listOf("финансовый сектор", "финансовые операции", "кредитный лимит", "банк", "инвестиции")),
        Rule("ПРОФИЛЬ", listOf("уровень профиля", "статистика профиля", "профиль игрока")),
        Rule("ГАРАЖ", listOf("твой личный гараж", "личный гараж", "места в гараже", "расширить гараж")),
        Rule("МАГАЗИН_УСЛУГ", listOf("автомойка", "малярный цех", "шиномонтаж 24/7", "детейлинг", "запчасти")),
        Rule("КОНТРАКТ_ЗАДАНИЕ", listOf("контракт", "заказ", "квест", "миссия", "задание")),
        Rule("НАГРАДА", listOf("награда", "бонус", "приз", "выигрыш", "reward", "bonus")),
        Rule("ПРОДАЖА", listOf("предложение покупателя", "продать авто", "машина продана", "продажа автомобиля", "продан")),
        Rule("ПОКУПКА", listOf("купить авто", "покупка автомобиля", "цена покупки", "автомобиль куплен", "buy")),
        Rule("УЛУЧШЕНИЕ", listOf("ремонт", "полировка", "окраска", "турбина", "чип", "тюнинг", "улучшение", "диагностика", "шины", "тормоза", "подвеска")),
        Rule("СОРЕВНОВАНИЕ", listOf("соревнование", "испытание", "challenge"))
    )

    fun classify(text: String): String {
        val s = text.lowercase()
        val match = rules.firstOrNull { rule ->
            val hits = rule.words.count { s.contains(it) }
            hits >= rule.minHits
        }
        if (match != null) return match.type
        if (GameParser.plateAuction(text)) return "АУКЦИОН_НОМЕРОВ"
        if (GameParser.name(text).isNotBlank() || GameParser.price(text) != null || GameParser.hp(text) != null || GameParser.plate(text).isNotBlank()) return "АВТО"
        return "ОБЗОР"
    }

    fun isNavigationSection(type: String): Boolean = type in setOf(
        "ПРОФИЛЬ", "ГАРАЖ", "СКЛАД_НОМЕРОВ", "РЫНОК_АВТО", "АВТОСАЛОН",
        "АУКЦИОН_НОМЕРОВ", "ИМПОРТ_ТАМОЖНЯ", "БИЗНЕСЫ", "РАБОТА", "КЛАНЫ",
        "ПАРЫ_С_КОНКУРЕНТАМИ", "УЛИЧНЫЕ_ГОНКИ", "РЕФЕРАЛЫ", "ГАРАЖНАЯ_НАГРАДА",
        "ТОП_ИГРОКОВ", "СХОДКА_У_ТЦ", "ЧАСТНЫЕ_АВТОРЫНКИ", "ФИНАНСОВЫЙ_СЕКТОР"
    )
}
